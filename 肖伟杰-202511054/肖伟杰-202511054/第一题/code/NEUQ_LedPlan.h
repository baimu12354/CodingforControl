/*********************************************************************************************************************
* 文件名称          NEUQ_LedPlan
* 组织名称          东北大学秦皇岛分校 智能车实验室
* 适用平台          STM32F407VE
*
* 功能              第一题 LED 时序控制：四套方案的时序引擎（每套完整周期严格 2 s）
*
* 方案表（一个完整周期内的动作，合计都是 2000 ms）
*   1   亮 1000 → 灭 1000
*   2   亮  200 → 灭 1800
*   3   亮  200 → 灭 200 → 亮 200 → 灭 1400
*   4   亮  200 → 灭 200 → 亮 600 → 灭 1000
*
* 关键设计（对应"按键和刷屏不得干扰当前周期"）
*   ① LED 电平只由"当前周期内已过时间 + 当前方案"查表得出，没有任何 Delay；
*   ② 按键只写"待执行方案"，绝不碰周期起点，也绝不碰 LED 引脚；
*   ③ 周期起点用 += 2000 固定步长累加（不是直接取 now），所以周期严格 2 s、永不漂移；
*   ④ 本引擎在 1 ms 节拍里调用，LED 动作与主循环刷屏完全解耦。
********************************************************************************************************************/
#ifndef NEUQ_LEDPLAN_H_
#define NEUQ_LEDPLAN_H_

#include "stm32f4xx_hal.h"

/* ------------------------- 可配置项 ------------------------- */
#define LED_PLAN_NUM        4U        /* 方案数量：1~4 */
#define LED_PLAN_PERIOD_MS  2000U     /* 每套方案完整周期：2 s */
#define LED_PLAN_PIN        PA8       /* 演示 LED（推挽输出，高电平点亮） */

/* 当前方案 / 待执行方案：单一数据源，菜单读的就是这两个变量 */
extern volatile int32_t g_led_plan_active;    /* 当前方案(1~4)，只在周期起点更新 */
extern volatile int32_t g_led_plan_pending;   /* 待执行方案(1~4)，按键修改，下一周期起点生效 */

/* ------------------------------ 接口 ------------------------------ */
void     NEUQ_LedPlan_Init(void);                /* 初始化 PA8 与时序引擎（上电即从方案 1 开始循环） */
void     NEUQ_LedPlan_Tick(uint32_t now_ms);     /* 每 1 ms 调用一次（放在 1 ms 中断节拍里） */
uint8_t  NEUQ_LedPlan_GetActive(void);           /* 读取当前方案 */
uint8_t  NEUQ_LedPlan_GetPending(void);          /* 读取待执行方案 */
uint16_t NEUQ_LedPlan_TotalMs(uint8_t plan);     /* 某方案一个周期的总时长（应为 2000） */

#endif /* NEUQ_LEDPLAN_H_ */
