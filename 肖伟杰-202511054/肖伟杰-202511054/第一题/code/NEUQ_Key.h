/*********************************************************************************************************************
* 文件名称          NEUQ_Key
* 组织名称          东北大学秦皇岛分校 智能车实验室
* 适用平台          STM32F407VE
*
* 功能              按键驱动：计数消抖 + 短按/长按事件（第一题 LED 时序控制）
*
* 设计要点
*   ① 计数消抖：每 10 ms 扫描一次，连续采到 4 次低电平才认为按下（约 40 ms），
*      单次抖动不会被当成一次按键；
*   ② 短按在"松手"时确认，按下不发事件 → 一次按下只产生一条 SHORT，不会连发；
*   ③ 长按按住满 1 s 后开始每 200 ms 重复发 LONG，方便连续加减方案号；
*   ④ 事件只在"按键"这一侧产生，和 LED 时序、LCD 刷新完全无关，
*      所以连续按键、长按、刷新页面都不会暂停/拉长/重置正在跑的 LED 动作。
********************************************************************************************************************/
#ifndef NEUQ_KEY_H_
#define NEUQ_KEY_H_

#include "stm32f4xx_hal.h"

/* ------------------------- 可配置项 ------------------------- */
#define KEY_SCAN_DIV        10U    /* 扫描分频：1 ms 节拍 × 10 = 每 10 ms 扫描一次 */
#define KEY_DEBOUNCE_CNT    4U     /* 连续 4 次低电平才认为按下（约 40 ms） */
#define KEY_LONG_CNT        100U   /* 100 × 10 ms = 1 s 起判长按 */
#define KEY_LONG_REPEAT_CNT 20U    /* 长按后每 20 × 10 ms = 200 ms 重复发一次 */
#define KEY_CNT_MAX         250U   /* 计数上限，防止溢出把"长按"误判成"松手" */

/* ------------------------- 事件定义 ------------------------- */
typedef enum
{
    KEY_EVENT_NONE = 0,     /* 无事件 */
    KEY_EVENT_SHORT,        /* 短按（松手时确认，一次按下只发一次） */
    KEY_EVENT_LONG,         /* 长按（按住满 1 s 后按固定节奏重复触发） */
} KeyEventEnum;

/* ------------------------- 按键编号（引脚按下为低、上拉输入） ------------------------- */
typedef enum
{
    KEY_ID_UP = 0,      /* PE9  方案 +1 */
    KEY_ID_DOWN,        /* PE7  方案 -1 */
    KEY_ID_FORWARD,     /* PE8  方案 +1（与 UP 等价） */
    KEY_ID_BACK,        /* PE10 方案 -1（与 DOWN 等价） */
    KEY_ID_K0,          /* PA0  板载按键，同"确认"，也按 +1 处理 */
    KEY_ID_NUM
} KeyIdEnum;

/* ------------------------------ 接口 ------------------------------ */
void         NEUQ_Key_Init(void);                     /* 所有按键配置成上拉输入 */
void         NEUQ_Key_Scan(void);                     /* 每 10 ms 调用一次（放在 1 ms 节拍里分频） */
KeyEventEnum NEUQ_Key_GetEvent(KeyIdEnum id);         /* 取走事件（读后自动清零） */

#endif /* NEUQ_KEY_H_ */
