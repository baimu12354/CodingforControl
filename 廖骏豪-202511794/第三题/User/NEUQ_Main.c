#include "../CODE/NEUQ_App.h"     // 第三题：串口调参与电机闭环控制

/*==============================================================================
 * 第三题：串口调参与电机闭环控制
 *   全部应用代码在 CODE 文件夹里，本文件只负责把应用跑起来：
 *     NEUQ_App_Init()  电机 PWM / 编码器 / 闭环 PID / 上位机串口 + 接收中断 / 5ms 控制节拍
 *     NEUQ_App_Loop()  主循环：解析上位机字节包 + 按节拍回传（闭环在中断里，不受通信影响）
 *
 *   注意：这里不调用 NEUQ_Debug_init() —— 它会把 UART_0 重新初始化，
 *         与上位机通信的配置冲突；调试信息全部通过字节包回传。
 *============================================================================*/
// **************************** 代码区域 ****************************
void User_Main(void){

    NEUQ_App_Init();            /* 上电状态 = 停止：PWM 0、方向脚低、等 START 命令 */

    NEUQ_App_Loop();            /* 不返回 */
}
