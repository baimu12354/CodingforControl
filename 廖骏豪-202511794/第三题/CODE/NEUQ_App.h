#ifndef _NEUQ_APP_H_
#define _NEUQ_APP_H_

/*  函数简介     第三题全部初始化
 *  使用示例     NEUQ_App_Init();
 *  备注         顺序：电机 -> 编码器 -> 闭环 -> 通信 -> 最后才启动控制中断节拍，
 *                保证第一个控制中断到来时所有外设都已就绪。                              */
void NEUQ_App_Init(void);

/*  函数简介     主循环：串口解析 + 按节拍回传（永远不返回）
 *  使用示例     NEUQ_App_Loop();
 *  备注         闭环控制完全在定周期中断里完成，这里做多久都不会影响控制曲线           */
void NEUQ_App_Loop(void);

#endif /* _NEUQ_APP_H_ */
