#include "NEUQ_Config.h"
#include "NEUQ_App.h"
#include "NEUQ_Motor.h"
#include "NEUQ_Speed.h"
#include "NEUQ_Control.h"
#include "NEUQ_Comm.h"

/*-------------------------------------------------------------------------------------------------------------------
* 函数简介       第三题初始化
* 参数说明       void
* 返回参数       void
* 使用示例       NEUQ_App_Init();
* 备注信息       ① 这里不调用 NEUQ_Debug_init()：
*                   NEUQ_Debug_init() 会把 UART_0 重新初始化为 115200，和上位机冲突。
*                   本题不需要文本打印，调试信息全部通过字节包回传给上位机。
*                ② 控制中断的优先级必须"低于"串口接收中断（数值更大）：
*                   控制中断里有浮点运算，若它优先级更高，会把串口接收中断压住，
*                   115200 波特率下一个字节只有 87us，可能造成接收溢出丢字节。
*                   让串口中断可以打断控制中断即可彻底避免丢包，
*                   而控制中断被打断只会带来几微秒的抖动，对电机控制没有影响。
*------------------------------------------------------------------------------------------------------------------*/
void NEUQ_App_Init(void)
{
    NEUQ_Delay_init();          /* 使能 DWT 延时（调试时可用 NEUQ_Delay_us/ms） */

    NEUQ_Motor_Init();            /* 电机 PWM + 方向，输出 0                    */
    NEUQ_Speed_Init();          /* 编码器接口 + 计数清零                      */
    NEUQ_Control_Init();          /* PID 与指令邮箱，上电状态 = 停止等待启动     */
    NEUQ_Comm_Init();             /* 上位机串口 + 接收中断                      */

    /* 最后启动定周期控制节拍，此后 NEUQ_Control_ISR 每 NEUQ_CONTROL_PERIOD_MS 执行一次 */
    NEUQ_PIT_init_ms(NEUQ_PIT_CHANNEL, NEUQ_CONTROL_PERIOD_MS);

#if (NEUQ_PIT_CHANNEL_INDEX == 1)
    HAL_NVIC_SetPriority(TIM6_DAC_IRQn, NEUQ_CONTROL_IRQ_PRIO, 0);
#else
    HAL_NVIC_SetPriority(TIM7_IRQn, NEUQ_CONTROL_IRQ_PRIO, 0);
#endif
}

/*-------------------------------------------------------------------------------------------------------------------
* 函数简介       主循环
* 参数说明       void
* 返回参数       void（不返回）
* 使用示例       NEUQ_App_Loop();
* 备注信息       串口解析与上传全部放在主循环：
*                 · 收：字节中断 -> 环形缓冲 -> 这里逐字节状态机解包
*                 · 发：按控制节拍组帧上传
*               闭环控制不在这里，因此无论通信多忙、上位机是否连着，电机控制都不会中断。
*------------------------------------------------------------------------------------------------------------------*/
void NEUQ_App_Loop(void)
{
    for (;;)
    {
        NEUQ_Comm_Poll();         /* 解析上位机字节包，解包成功后更新目标/启停/PID */
        NEUQ_Comm_Upload();       /* 按节拍回传目标转速、实际转速、当前生效 PID 参数 */
    }
}
