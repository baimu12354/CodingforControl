#ifndef __NEUQ_MAIN_H__
#define __NEUQ_MAIN_H__

#include "NEUQ_lib_include.h"

void User_Main(void);

/* ==========================================================================
 * 串口协议 + VOFA+ 上传曲线（原 NEUQ_VOFA 模块，已并入 NEUQ_Main）
 *
 *   下行（上位机 -> 单片机）：0xAA 0x55 CMD [DATA...]（无长度字节）
 *   上行（单片机 -> 上位机）：VOFA+ JustFloat，5 通道（目标/实际/Kp/Ki/Kd），20ms 一帧
 *   回传参数和曲线共用这一条流，不要再往 UART_0 上 printf 文本，否则会错帧。
 * ========================================================================== */
void NEUQ_VOFA_INIT(void);             // 初始化接收 FIFO，开启串口接收中断
void NEUQ_VOFA_RecvByte(uint8_t dat);  // 中断里调用：每收到 1 字节就丢进 FIFO
void NEUQ_VOFA_Process(void);          // 主循环调用：从 FIFO 取字节、解包、执行指令
void NEUQ_VOFA_Send(void);             // 主循环调用：每 20ms 向 VOFA+ 上传 5 通道曲线

#endif  /* __NEUQ_MAIN_H__ */