#ifndef _TASK_CONFIG_H_
#define _TASK_CONFIG_H_

//====================================================================================================================
// 一、本分支只包含第二题 陀螺仪六轴数据处理 + 四元数姿态解算，TASK_SELECT 固定为 2（代码中用它区分题目，不要修改）
//====================================================================================================================
#define TASK_SELECT                     (2)

//====================================================================================================================
// 二、菜单按键（第一题、第二题使用）
//     按 22 届校赛主板原理图：四个按键接 PE7 / PE8 / PE9 / PE10，板上有 4.7k 上拉，按下接地为低电平。
//     哪个键对应哪个功能不顺手，直接对调下面的引脚即可。
//     只接 上 / 下 / 确认 三个键也能完整操作所有菜单，返回键只是快捷键
//====================================================================================================================
#define KEY_UP_PIN                      (PE10)          // 上 / 数值增大
#define KEY_UP_ACTIVE_LEVEL             (GPIO_Low)      // 按下时引脚是低电平
#define KEY_DOWN_PIN                    (PE8)           // 下 / 数值减小
#define KEY_DOWN_ACTIVE_LEVEL           (GPIO_Low)
#define KEY_OK_PIN                      (PE7)           // 确认 / 进入
#define KEY_OK_ACTIVE_LEVEL             (GPIO_Low)
#define KEY_BACK_PIN                    (PE9)           // 返回 / 取消
#define KEY_BACK_ACTIVE_LEVEL           (GPIO_Low)

#define KEY_SCAN_PERIOD_MS              (10)            // 每 10 ms 扫描一次按键
#define KEY_DEBOUNCE_COUNT              (3)             // 连续 3 次读到相同状态才算数，即 30 ms 消抖
#define KEY_REPEAT_DELAY_MS             (500)           // 上/下键按住 500 ms 后开始连发
#define KEY_REPEAT_PERIOD_MS            (100)           // 连发时每 100 ms 触发一次

//====================================================================================================================
// 四、第二题：陀螺仪六轴数据处理 + 四元数姿态解算
//     MPU6050 由库固定接在硬件 IIC3（SCL=PA8，SDA=PC9），量程由库决定：加速度 ±8 g，角速度 ±2000 dps
//     滤波参数存在板载 W25Q16（SPI1：PA5/PA6/PA7，片选 PB0）
//====================================================================================================================
#define T2_SAMPLE_PERIOD_MS             (5)             // 每 5 ms 采样一次（200 Hz），滤波和姿态也按这个周期更新
#define T2_VOFA_UART                    (UART_0)        // 发波形给 VOFA+ 的串口：核心板 PA9(TX)/PA10(RX)，115200，JustFloat
#define T2_FLASH_SECTOR                 (511U)          // 参数存在 W25Q16 的最后一个扇区（4 KB）

#define T2_DEFAULT_ACC_CUTOFF_HZ        (5.0f)          // Flash 里没有保存过参数时的默认截止频率：加速度
#define T2_DEFAULT_GYRO_CUTOFF_HZ       (10.0f)         // Flash 里没有保存过参数时的默认截止频率：角速度
#define T2_CUTOFF_MIN_HZ                (0.5f)          // 截止频率可调范围
#define T2_CUTOFF_MAX_HZ                (50.0f)
#define T2_CUTOFF_STEP_HZ               (0.5f)          // 菜单里每按一次加 / 减多少

#define T2_CALIB_TIME_MS                (2000U)         // 陀螺仪零偏校准：静止采集 2 s
#define T2_CALIB_MOTION_LIMIT_DPS       (2.0f)          // 校准期间角速度波动超过 2 dps 说明被碰到了，自动重新开始
#define T2_MAHONY_KP                    (1.0f)          // 姿态融合时加速度计的修正强度，越大越相信加速度计
#define T2_GYRO_DEADBAND_DPS            (0.10f)         // 去掉零偏后小于 0.1 dps 的角速度当作 0，防止静止时航向慢慢漂

#endif
