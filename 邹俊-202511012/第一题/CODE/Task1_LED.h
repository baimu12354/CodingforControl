/*********************************************************************************************************************
* 文件名称          Task1_LED
* 功能说明          第一题：LED 时序控制（单页 LCD 菜单 + 按键选方案）
*
*                   资源分配（谁在什么时候做什么）：
*                   TIM6 定时中断（PIT_CH1），每 1 ms 一次：
*                       · 决定这 1 ms LED 亮还是灭，并写 PA8           —— LED 节拍只由这里决定
*                       · 亮灯 / 灭灯计数各加 1 ms，屏幕上能直接看到每一段亮、灭了多久
*                       · 每 10 次（10 ms）扫描一次按键
*                   主循环：
*                       · 处理按键事件（移动光标、设置待执行方案）
*                       · 每 100 ms（或按键后立即）刷新屏幕
*                   主循环里的任何操作都只会被中断打断，不可能反过来影响 LED 的节拍
*
* 修改记录
* 日期              备注
* 2026-09-27        first version
********************************************************************************************************************/
