#ifndef _TASK_CONFIG_H_
#define _TASK_CONFIG_H_

//====================================================================================================================
// 一、本分支只包含第一题 LED 时序控制，TASK_SELECT 固定为 1（代码中用它区分题目，不要修改）
//====================================================================================================================
#define TASK_SELECT                     (1)

//====================================================================================================================
// 二、菜单按键（第一题、第二题使用）
//     按 22 届校赛主板原理图：四个按键接 PE7 / PE8 / PE9 / PE10，板上有 4.7k 上拉，按下接地为低电平。
//     哪个键对应哪个功能不顺手，直接对调下面的引脚即可。
//     只接 上 / 下 / 确认 三个键也能完整操作所有菜单，返回键只是快捷键
//====================================================================================================================
#define KEY_UP_PIN                      (PE10)          // 上 / 数值增大
#define KEY_UP_ACTIVE_LEVEL             (GPIO_Low)      // 按下时引脚是低电平
#define KEY_DOWN_PIN                    (PE8)           // 下 / 数值减小
#define KEY_DOWN_ACTIVE_LEVEL           (GPIO_Low)
#define KEY_OK_PIN                      (PE7)           // 确认 / 进入
#define KEY_OK_ACTIVE_LEVEL             (GPIO_Low)
#define KEY_BACK_PIN                    (PE9)           // 返回 / 取消
#define KEY_BACK_ACTIVE_LEVEL           (GPIO_Low)

#define KEY_SCAN_PERIOD_MS              (10)            // 每 10 ms 扫描一次按键
#define KEY_DEBOUNCE_COUNT              (3)             // 连续 3 次读到相同状态才算数，即 30 ms 消抖
#define KEY_REPEAT_DELAY_MS             (500)           // 上/下键按住 500 ms 后开始连发
#define KEY_REPEAT_PERIOD_MS            (100)           // 连发时每 100 ms 触发一次

//====================================================================================================================
// 三、第一题：LED 时序控制
//====================================================================================================================
#define T1_LED_PIN                      (PA8)           // 任务书指定的 LED 引脚
#define T1_LED_ON_LEVEL                 (GPIO_High)     // LED 亮时的引脚电平
#define T1_LED_OFF_LEVEL                (GPIO_Low)      // LED 灭时的引脚电平（低电平点亮的板子把这两行对调）

#endif
