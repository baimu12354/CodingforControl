/*********************************************************************************************************************
* 文件名称          Task3_Motor
* 功能说明          第三题：串口字节包调参 + 电机速度闭环
*
*                   资源分配（谁在什么时候做什么）：
*                   TIM6 定时中断（PIT_CH1），每 5 ms 一次，优先级 0（最高）：
*                       读编码器 → 算转速 → PID → 更新 PWM 和方向；每 2 次（10 ms）把回传数据放进发送缓冲
*                   串口接收中断，优先级 3：每收到 1 个字节只把它放进接收缓冲，马上返回
*                   主循环：从接收缓冲取字节 → 协议解析 → 执行指令；把发送缓冲里的回传数据写到串口
*                   串口收发和解析都不在控制中断里，所以通信再频繁也不会让控制周期中断或变长
*
*                   回传（VOFA+ JustFloat，每 10 ms 一帧，10 个 float）：
*                   I0 目标转速（控制器实际跟踪的值，停止时为 0）  I1 实际转速      I2 上位机设定的目标转速
*                   I3 Kp   I4 Ki   I5 Kd                         I6 状态 0 停止 / 1 运行 / 2 故障
*                   I7 PWM 输出 %                                  I8 收到的有效帧数
*                   I9 最近一条指令的结果 0 成功 / 1 未停止而不允许改 PID / 2 数值不合法 / 3 命令或长度错误
*                   单位：转速 rpm（输出轴每分钟转数）
*
* 修改记录
* 日期              备注
* 2026-09-27        first version
********************************************************************************************************************/
