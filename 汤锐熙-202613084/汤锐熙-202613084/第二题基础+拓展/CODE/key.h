/*********************************************************************************************************************
* 文件名称   key
* 功能说明   按键扫描：消抖 + 长按连发，供菜单系统使用
* 使用方法   Key_Init() 开机调用一次；Key_Scan() 在主循环里反复调用
*********************************************************************************************************************/
#ifndef _KEY_H_
#define _KEY_H_

#include "NEUQ_lib_include.h"

// 按键事件：菜单引擎只认这些标签
typedef enum {
    KEY_NONE = 0,   // 没有按键
    KEY_UP,         // 上键
    KEY_DOWN,       // 下键
    KEY_OK,         // 确定键
    KEY_BACK,       // 返回键
} KeyEvent_t;

// 初始化按键引脚为“输入上拉”（开机调用一次）
void Key_Init(void);
// 扫描按键，返回本次按键事件（内部已做消抖与长按连发）
KeyEvent_t Key_Scan(void);

#endif
