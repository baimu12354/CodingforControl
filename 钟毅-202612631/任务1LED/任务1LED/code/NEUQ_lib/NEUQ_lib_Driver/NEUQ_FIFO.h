#ifndef _NEUQ_FIFO_H_
#define _NEUQ_FIFO_H_

#include <stdint.h>

#define NEUQ_FIFO_OK       (1U)
#define NEUQ_FIFO_ERROR    (0U)

// 函数返回值：成功返回NEUQ_FIFO_OK，参数错误或操作失败返回NEUQ_FIFO_ERROR
typedef struct
{
    uint8_t *buffer;        // FIFO实际存储数组，由用户提供
    uint32_t size;          // FIFO总容量，单位为字节
    volatile uint32_t head; // 写入位置索引
    volatile uint32_t tail; // 读取位置索引
} NEUQ_FIFO_t;

// 该FIFO采用双周期索引，可使用完整buffer容量，适用于一个生产者和一个消费者。

//==============================================================================================
// 函数名称 : NEUQ_FIFO_init
// 函数功能 : 初始化软件FIFO；FIFO不在内部申请存储空间
// 输入参数 : fifo : FIFO管理结构体；buffer : 用户提供的存储数组；size : 数组大小（字节）
// 返回值   : 无。buffer为空或size为0时，后续读写操作返回错误
// 使用示例 : uint8_t buf[256]; NEUQ_FIFO_t fifo; NEUQ_FIFO_init(&fifo,buf,sizeof(buf));
//==============================================================================================
void NEUQ_FIFO_init(NEUQ_FIFO_t *fifo, uint8_t *buffer, uint32_t size);

//==============================================================================================
// 函数名称 : NEUQ_FIFO_clear
// 函数功能 : 清空FIFO，保留原有存储数组
// 输入参数 : fifo : FIFO管理结构体指针
// 返回值   : 无
// 注意事项 : 不能与同一个FIFO的读写操作并发调用
//==============================================================================================
void NEUQ_FIFO_clear(NEUQ_FIFO_t *fifo);

//==============================================================================================
// 函数名称 : NEUQ_FIFO_write_byte / NEUQ_FIFO_read_byte
// 函数功能 : 写入或读取一个字节；读取成功后该字节从FIFO移除
// 返回值   : NEUQ_FIFO_OK表示成功，NEUQ_FIFO_ERROR表示满、空或参数错误
//==============================================================================================
uint8_t NEUQ_FIFO_write_byte(NEUQ_FIFO_t *fifo, uint8_t data);
uint8_t NEUQ_FIFO_read_byte(NEUQ_FIFO_t *fifo, uint8_t *data);

//==============================================================================================
// 函数名称 : NEUQ_FIFO_peek_byte
// 函数功能 : 查看最早写入的一个字节，但不移动读取位置
// 返回值   : NEUQ_FIFO_OK表示成功，NEUQ_FIFO_ERROR表示FIFO为空或参数错误
//==============================================================================================
uint8_t NEUQ_FIFO_peek_byte(NEUQ_FIFO_t *fifo, uint8_t *data);

//==============================================================================================
// 函数名称 : NEUQ_FIFO_write / NEUQ_FIFO_read
// 函数功能 : 批量写入或读取数据，空间或数据不足时允许部分完成
// 返回值   : 实际写入或读取的字节数
//==============================================================================================
uint32_t NEUQ_FIFO_write(NEUQ_FIFO_t *fifo, const uint8_t *data, uint32_t length);
uint32_t NEUQ_FIFO_read(NEUQ_FIFO_t *fifo, uint8_t *data, uint32_t length);

//==============================================================================================
// 函数名称 : NEUQ_FIFO_peek
// 函数功能 : 查看FIFO中的一段数据，但不移动读取位置
// 返回值   : 实际查看的字节数
//==============================================================================================
uint32_t NEUQ_FIFO_peek(NEUQ_FIFO_t *fifo, uint8_t *data, uint32_t length);

//==============================================================================================
// 函数名称 : NEUQ_FIFO_write_all / NEUQ_FIFO_read_all
// 函数功能 : 完整写入或读取；空间或数据不足时不移动FIFO指针
// 返回值   : NEUQ_FIFO_OK表示完整成功，NEUQ_FIFO_ERROR表示失败
//==============================================================================================
uint8_t NEUQ_FIFO_write_all(NEUQ_FIFO_t *fifo, const uint8_t *data, uint32_t length);
uint8_t NEUQ_FIFO_read_all(NEUQ_FIFO_t *fifo, uint8_t *data, uint32_t length);

//==============================================================================================
// 函数名称 : NEUQ_FIFO_drop
// 函数功能 : 丢弃FIFO中最早的指定长度数据
// 返回值   : 实际丢弃的字节数
//==============================================================================================
uint32_t NEUQ_FIFO_drop(NEUQ_FIFO_t *fifo, uint32_t length);

//==============================================================================================
// 函数名称 : NEUQ_FIFO_get_used / NEUQ_FIFO_get_free / NEUQ_FIFO_get_size
// 函数功能 : 查询已使用空间、剩余空间和FIFO总容量
// 返回值   : 对应字节数；参数错误时返回0
//==============================================================================================
uint32_t NEUQ_FIFO_get_used(NEUQ_FIFO_t *fifo);
uint32_t NEUQ_FIFO_get_free(NEUQ_FIFO_t *fifo);
uint32_t NEUQ_FIFO_get_size(NEUQ_FIFO_t *fifo);

//==============================================================================================
// 函数名称 : NEUQ_FIFO_is_empty / NEUQ_FIFO_is_full
// 函数功能 : 判断FIFO是否为空或已满
// 返回值   : 1表示是，0表示否或参数错误
//==============================================================================================
uint8_t NEUQ_FIFO_is_empty(NEUQ_FIFO_t *fifo);
uint8_t NEUQ_FIFO_is_full(NEUQ_FIFO_t *fifo);

//==============================================================================================
// 函数名称 : NEUQ_FIFO_get_read_block / NEUQ_FIFO_get_write_block
// 函数功能 : 获取内部连续可读或可写数据块的地址和长度，适合DMA
// 返回值   : 连续块长度；无数据或参数错误时返回0，data置为NULL
//==============================================================================================
uint32_t NEUQ_FIFO_get_read_block(NEUQ_FIFO_t *fifo, uint8_t **data);
uint32_t NEUQ_FIFO_get_write_block(NEUQ_FIFO_t *fifo, uint8_t **data);

//==============================================================================================
// 函数名称 : NEUQ_FIFO_commit_write
// 函数功能 : 确认外部已经写入连续可写块的数据长度
// 返回值   : 实际确认长度，不超过当前连续可写块长度
// 使用示例 : uint8_t *ptr; uint32_t len=NEUQ_FIFO_get_write_block(&fifo,&ptr);
//            /* DMA向ptr写入len字节后 */ NEUQ_FIFO_commit_write(&fifo,len);
//==============================================================================================
uint32_t NEUQ_FIFO_commit_write(NEUQ_FIFO_t *fifo, uint32_t length);

// 使用要点：FIFO本身不分配内存；典型用法为串口中断写入、主循环读取。
// clear和DMA块指针的使用需要由用户保证，不能与对应读写操作并发。

#endif
