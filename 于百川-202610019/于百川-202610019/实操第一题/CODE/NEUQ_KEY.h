/*********************************************************************************************************************
 * NEUQ_KEY —— 独立按键模块（消抖 + 沿触发 + 事件消费）【第一题配套】
 *
 * 设计要点：
 *   1. 采样 / 消抖放在 1ms 定时中断（KEY_Scan）里完成，
 *      消抖时长固定 = 连续 5 次采样 = 5ms，不依赖主循环的调度速度，
 *      按键响应时间确定，主循环被其他任务拖慢也不影响消抖。
 *   2. 中断只负责"产生按键事件"（写 key_event），主循环通过
 *      NEUQ_KEY_Get() 消费事件；中断与主循环之间用 volatile 单字节
 *      变量传递事件（Cortex-M 上单字节对齐读写是原子的）。
 *   3. 沿触发：每次"按下沿"只产生一次事件；长按不连发；松开后
 *      reported 清零，再次按下可再次触发 —— 满足题目
 *      "连续按键、长按不得反复重置当前动作"的要求。
 *   4. 纯 C 实现，不依赖 C++；只调用 NEUQ 库的 GPIO 接口。
 *
 * 接线约定（低有效：按键一端接引脚、另一端接 GND，按下时引脚读到低电平）：
 *   KEY_UP_PIN   = PE9   （NEUQ 板载按键：KEY_UP，与库例程一致）
 *   KEY_DOWN_PIN = PE8   （NEUQ 板载按键：KEY_DOWN，与库例程一致）
 *   若你的板子按键是"按下接 3V3（高有效）"，请把 KEY_Scan 中的
 *   GPIO_Low 判断改成 GPIO_High，并把 NEUQ_KEY_Init 里的上拉改成下拉。
 ********************************************************************************************************************/
#ifndef _NEUQ_KEY_H_              /* 头文件保护宏：防止同一文件被多次 #include 时发生重复定义 */
#define _NEUQ_KEY_H_              /* 定义保护宏：第二次 #include 时因已定义而整段跳过 */

/* ============================ 1. 引脚定义（低有效：按下 = 低电平） ============================ */
#define KEY_UP_PIN      PE9       
#define KEY_DOWN_PIN    PE8       

/* ============================ 2. 按键事件值定义 ============================ */
#define KEY_NONE        0         /* 无事件：主循环每次查询的默认返回，表示没有可消费的按键事件 */
#define KEY_UP          1         /* 事件：上键被按下沿触发一次，主循环应把待执行方案 -1 */
#define KEY_DOWN        2         /* 事件：下键被按下沿触发一次，主循环应把待执行方案 +1 */

/* ============================ 3. 接口声明（供其他 .c 文件调用） ============================ */
void    NEUQ_KEY_Init(void);      /* 初始化按键 GPIO：两个引脚设为上拉输入（低有效） */
void    KEY_Scan(void);      /* 1ms 中断里调用：采样 + 消抖 + 沿触发，写入按键事件 */
uint8_t NEUQ_KEY_Get(void);       /* 主循环调用：取走（消费）一次按键事件并清零；无事件返回 KEY_NONE */

#endif /* _NEUQ_KEY_H_ */         /* 结束头文件保护 */
