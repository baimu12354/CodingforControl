/*********************************************************************************************************************
* 本文件是第二题「四元数姿态解算」挑战部分新增的代码
* 基于 NEUQ Library 编写，仅使用库提供的 MPU6050 读取函数和 math.h 数学函数
*
* 作用：用四元数（Mahony 互补滤波）把 MPU6050 的加速度 + 角速度
*       融合成三个欧拉角：横滚角 / 俯仰角 / 航向角
*
* 坐标轴约定（与 MPU6050 芯片坐标系一致）：
*   X 轴 —— 横滚 Roll  （绕 X 轴旋转）
*   Y 轴 —— 俯仰 Pitch （绕 Y 轴旋转）
*   Z 轴 —— 航向 Yaw   （绕 Z 轴旋转，水平原地转）
* 角度单位：度（°）
*
* 姿态更新周期：跟随主循环，每采到一组数据就解算一次（约 0.5~1ms 一次，
*                内部用 NEUQ 库的微秒计时器实际测量时间差 dt，不依赖固定周期）
********************************************************************************************************************/
#ifndef __NEUQ_ATTITUDE_H
#define __NEUQ_ATTITUDE_H

// 三个姿态角输出（单位：度），供菜单页面显示
extern float att_roll;   // 横滚角
extern float att_pitch;  // 俯仰角
extern float att_yaw;    // 航向角（相对上电初始方向）

// 静置校准：上电时让模块保持静止，采样陀螺仪求零偏，
// 并把四元数初始化成单位四元数。应在 MPU6050 初始化之后调用一次。
void NEUQ_Attitude_Init(void);

// 手动重新校准：与上电校准相同（采样零偏 + 姿态角清零），
// 之后可在菜单里长按按键调用。调用时模块同样需保持静止。
void NEUQ_Attitude_Calibrate(void);

// 四元数姿态解算：每采到一组新数据后调用一次。
// acc_g   : 三轴加速度，单位 g（直接用 MPU6050_acc_transition 的结果）
// gyro_deg: 三轴角速度，单位 °/s（直接用 MPU6050_gyro_transition 的结果）
void NEUQ_Attitude_Solve(float acc_g[3], float gyro_deg[3]);

#endif
